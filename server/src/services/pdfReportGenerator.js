import PDFDocument from 'pdfkit'
import fs from 'fs'
import path from 'path'

// ── Colours & typography ──────────────────────────────────────────────────────
const BRAND_GREEN  = '#166534'
const LIGHT_GREEN  = '#dcfce7'
const DARK_GREY    = '#1e293b'
const MID_GREY     = '#64748b'
const LIGHT_GREY   = '#f1f5f9'
const BORDER_GREY  = '#e2e8f0'
const SCOPE_COLORS = { 'Scope 1': '#166534', 'Scope 2': '#2563eb', 'Scope 3': '#ca8a04' }

const FONT_REGULAR = 'Helvetica'
const FONT_BOLD    = 'Helvetica-Bold'

// ── Helpers ───────────────────────────────────────────────────────────────────

function fmt(n, dp = 2) {
  return Number(n ?? 0).toLocaleString('en-US', { minimumFractionDigits: dp, maximumFractionDigits: dp })
}

function fmtDate(d) {
  return new Date(d).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
}

function drawHRule(doc, y, colour = BORDER_GREY) {
  doc.moveTo(50, y).lineTo(doc.page.width - 50, y).strokeColor(colour).lineWidth(0.5).stroke()
}

function sectionTitle(doc, text) {
  doc.moveDown(0.6)
  doc.font(FONT_BOLD).fontSize(11).fillColor(BRAND_GREEN).text(text.toUpperCase())
  drawHRule(doc, doc.y + 3, BRAND_GREEN)
  doc.moveDown(0.5)
}

/**
 * Draw a simple table.
 * @param {PDFDocument} doc
 * @param {{ headers: string[], rows: (string|number)[][], colWidths: number[] }} opts
 */
function drawTable(doc, { headers, rows, colWidths }) {
  const startX = 50
  let y = doc.y
  const rowH = 20
  const pageBottom = doc.page.height - doc.page.margins.bottom - 10

  // Header row
  doc.rect(startX, y, colWidths.reduce((a, b) => a + b, 0), rowH).fill(BRAND_GREEN)
  let x = startX
  headers.forEach((h, i) => {
    doc.font(FONT_BOLD).fontSize(9).fillColor('white')
       .text(h, x + 4, y + 6, { width: colWidths[i] - 8, align: i === 0 ? 'left' : 'right' })
    x += colWidths[i]
  })
  y += rowH

  // Data rows
  rows.forEach((row, ri) => {
    // Page break check
    if (y + rowH > pageBottom) {
      doc.addPage()
      y = doc.page.margins.top
    }
    const bg = ri % 2 === 0 ? 'white' : LIGHT_GREY
    doc.rect(startX, y, colWidths.reduce((a, b) => a + b, 0), rowH).fill(bg)
    x = startX
    row.forEach((cell, ci) => {
      doc.font(FONT_REGULAR).fontSize(9).fillColor(DARK_GREY)
         .text(String(cell), x + 4, y + 6, { width: colWidths[ci] - 8, align: ci === 0 ? 'left' : 'right' })
      x += colWidths[ci]
    })
    // bottom border
    doc.moveTo(startX, y + rowH)
       .lineTo(startX + colWidths.reduce((a, b) => a + b, 0), y + rowH)
       .strokeColor(BORDER_GREY).lineWidth(0.3).stroke()
    y += rowH
  })

  doc.y = y + 6
}

// ── Cover page ────────────────────────────────────────────────────────────────

function drawCover(doc, { orgName, periodStart, periodEnd, generatedBy }) {
  // Green header band
  doc.rect(0, 0, doc.page.width, 180).fill(BRAND_GREEN)

  doc.font(FONT_BOLD).fontSize(26).fillColor('white')
     .text('Carbon Emissions Report', 50, 60, { align: 'center' })

  doc.font(FONT_REGULAR).fontSize(12).fillColor(LIGHT_GREEN)
     .text('GHG Protocol – Scope 1, 2 & 3 Summary', 50, 100, { align: 'center' })

  // Meta card
  const cardY = 200
  doc.rect(50, cardY, doc.page.width - 100, 130).fill(LIGHT_GREY)

  doc.font(FONT_BOLD).fontSize(10).fillColor(MID_GREY).text('ORGANIZATION', 70, cardY + 16)
  doc.font(FONT_BOLD).fontSize(14).fillColor(DARK_GREY).text(orgName, 70, cardY + 30)

  doc.font(FONT_BOLD).fontSize(10).fillColor(MID_GREY).text('REPORTING PERIOD', 70, cardY + 60)
  doc.font(FONT_REGULAR).fontSize(12).fillColor(DARK_GREY)
     .text(`${fmtDate(periodStart)}  –  ${fmtDate(periodEnd)}`, 70, cardY + 74)

  doc.font(FONT_BOLD).fontSize(10).fillColor(MID_GREY).text('GENERATED BY', 70, cardY + 104)
  doc.font(FONT_REGULAR).fontSize(11).fillColor(DARK_GREY).text(generatedBy, 70, cardY + 118)

  // Footer note
  doc.font(FONT_REGULAR).fontSize(8).fillColor(MID_GREY)
     .text(`Generated on ${fmtDate(new Date())}`, 50, doc.page.height - 60, { align: 'center' })
}

// ── Executive summary section ─────────────────────────────────────────────────

function drawExecutiveSummary(doc, { totalCO2e, byScope, recordCount }) {
  sectionTitle(doc, '1. Executive Summary')

  // Stat boxes
  const boxes = [
    { label: 'Total CO₂e (kg)', value: fmt(totalCO2e) },
    { label: 'Consumption Records', value: fmt(recordCount, 0) },
    { label: 'Scope 1 CO₂e (kg)', value: fmt(byScope.find((s) => s.scope === 'Scope 1')?.co2e ?? 0) },
    { label: 'Scope 2 CO₂e (kg)', value: fmt(byScope.find((s) => s.scope === 'Scope 2')?.co2e ?? 0) },
    { label: 'Scope 3 CO₂e (kg)', value: fmt(byScope.find((s) => s.scope === 'Scope 3')?.co2e ?? 0) },
  ]

  const boxW = 95
  const boxH = 52
  const startX = 50
  let bx = startX
  const by = doc.y

  boxes.forEach((b) => {
    doc.rect(bx, by, boxW, boxH).fill(LIGHT_GREY)
    doc.font(FONT_BOLD).fontSize(14).fillColor(BRAND_GREEN)
       .text(b.value, bx + 4, by + 10, { width: boxW - 8, align: 'center' })
    doc.font(FONT_REGULAR).fontSize(7).fillColor(MID_GREY)
       .text(b.label, bx + 4, by + 32, { width: boxW - 8, align: 'center' })
    bx += boxW + 6
  })

  doc.y = by + boxH + 12
}

// ── Scope breakdown section ───────────────────────────────────────────────────

function drawScopeBreakdown(doc, { byScope, totalCO2e }) {
  sectionTitle(doc, '2. Emissions by GHG Scope')

  doc.font(FONT_REGULAR).fontSize(9).fillColor(MID_GREY)
     .text(
       'Scope 1: direct combustion (diesel, petrol, natural gas). ' +
       'Scope 2: purchased electricity. Scope 3: indirect (water & other).',
       { lineGap: 2 },
     )
  doc.moveDown(0.4)

  const rows = byScope.map((s) => {
    const pct = totalCO2e > 0 ? ((s.co2e / totalCO2e) * 100).toFixed(1) : '0.0'
    return [s.scope, fmt(s.co2e), `${pct}%`]
  })

  drawTable(doc, {
    headers: ['Scope', 'CO₂e (kg)', '% of Total'],
    rows,
    colWidths: [200, 150, 150],
  })
}

// ── Source type section ───────────────────────────────────────────────────────

function drawByType(doc, { byType }) {
  sectionTitle(doc, '3. Emissions by Source Type')
  const rows = byType.map((t) => [t.type, fmt(t.co2e)])
  drawTable(doc, {
    headers: ['Source Type', 'CO₂e (kg)'],
    rows,
    colWidths: [250, 250],
  })
}

// ── Facility breakdown section ────────────────────────────────────────────────

function drawByFacility(doc, { byFacility, totalCO2e }) {
  sectionTitle(doc, '4. Emissions by Facility')
  const rows = byFacility.map((f) => {
    const pct = totalCO2e > 0 ? ((f.co2e / totalCO2e) * 100).toFixed(1) : '0.0'
    return [f.facilityName, fmt(f.co2e), `${pct}%`]
  })
  drawTable(doc, {
    headers: ['Facility', 'CO₂e (kg)', '% of Total'],
    rows,
    colWidths: [200, 150, 150],
  })
}

// ── Monthly trend section ─────────────────────────────────────────────────────

function drawTrend(doc, { trend }) {
  sectionTitle(doc, '5. Monthly Emissions Trend')
  const rows = trend.map((t) => [t.month, fmt(t.co2e)])
  drawTable(doc, {
    headers: ['Month', 'CO₂e (kg)'],
    rows,
    colWidths: [250, 250],
  })
}

// ── Methodology note ──────────────────────────────────────────────────────────

function drawMethodology(doc) {
  sectionTitle(doc, '6. Methodology & Data Sources')
  doc.font(FONT_REGULAR).fontSize(9).fillColor(DARK_GREY).text(
    'Emissions are calculated by multiplying consumption quantities by region-specific emission ' +
    'factors sourced from government publications (e.g. UK DESNZ, IEA, US EPA). ' +
    'CO₂e values are expressed in kilograms. ' +
    'GHG scopes follow the World Resources Institute / World Business Council for Sustainable ' +
    'Development (WRI/WBCSD) GHG Protocol Corporate Accounting and Reporting Standard.',
    { lineGap: 3 },
  )
}

// ── Main export ───────────────────────────────────────────────────────────────

/**
 * Generate a GHG Protocol PDF report and write it to disk.
 *
 * @param {{
 *   orgName: string,
 *   periodStart: Date,
 *   periodEnd: Date,
 *   generatedBy: string,
 *   trend: Array,
 *   byScope: Array,
 *   byType: Array,
 *   byFacility: Array,
 *   totalCO2e: number,
 *   recordCount: number,
 * }} data
 * @param {string} outputPath  Absolute file path to write the PDF.
 * @returns {Promise<void>}
 */
export function generatePDF(data, outputPath) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A4',
      margins: { top: 50, bottom: 50, left: 50, right: 50 },
      autoFirstPage: false,
      bufferPages: true, // keep all pages in memory so switchToPage works
    })
    const stream = fs.createWriteStream(outputPath)

    doc.pipe(stream)
    stream.on('error', reject)
    stream.on('finish', resolve)

    // ── Page 1: Cover ─────────────────────────────────────────────────────────
    doc.addPage()
    drawCover(doc, data)

    // ── Page 2+: Content ──────────────────────────────────────────────────────
    doc.addPage()

    doc.font(FONT_BOLD).fontSize(9).fillColor(MID_GREY)
       .text(`${data.orgName}  |  ${fmtDate(data.periodStart)} – ${fmtDate(data.periodEnd)}`, { align: 'right' })
    doc.moveDown(0.3)

    drawExecutiveSummary(doc, data)
    drawScopeBreakdown(doc, { byScope: data.byScope, totalCO2e: data.totalCO2e })
    drawByType(doc, { byType: data.byType })
    drawByFacility(doc, { byFacility: data.byFacility, totalCO2e: data.totalCO2e })
    drawTrend(doc, { trend: data.trend })
    drawMethodology(doc)

    // Footer on every page — use bufferedPageRange() correctly
    const range = doc.bufferedPageRange()  // { start, count }
    const totalPages = range.count

    for (let i = 0; i < totalPages; i++) {
      doc.switchToPage(range.start + i)
      if (i === 0) continue // skip cover page footer
      doc.font(FONT_REGULAR).fontSize(7).fillColor(MID_GREY)
         .text(
           `Page ${i + 1} of ${totalPages}  |  Carbon Tracker  |  Confidential`,
           50,
           doc.page.height - 40,
           { align: 'center' },
         )
    }

    doc.end()
  })
}
